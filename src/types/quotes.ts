/** Shape of the JSON payload the public quote page POSTs when the
 *  recipient clicks Accept / Decline. Used by the public API route. */
export interface QuoteRespondPayload {
  action: "accept" | "decline";
  /** Required when action === "decline". */
  reason?: DeclineReason;
  /** Required when reason === "Other". Optional otherwise. */
  note?: string;
  /** Required for accept when the quote requires a signature. */
  signerName?: string;
  /** Must be true for a signed accept. */
  agreedToTerms?: boolean;
  /** Required for a signed accept: computeQuoteDocumentHash of the content
   *  the page rendered, so the signature binds to what the signer saw. */
  documentHash?: string;
}

/** See `Quote.paidVia`. */
export type QuotePaidVia =
  | { rail: "paystack_link"; linkId: string; reference: string }
  /** A recurring schedule charged its saved card (W5). */
  | { rail: "paystack_auto"; mandateId: string; reference: string }
  /** Paid by card through the sub-account's own Stripe (`orders/{orderId}`). */
  | { rail: "stripe_order"; orderId: string };

/**
 * A recurring card cycle's charge, for the operator: `pending` until the
 * webhook records it, `unknown` when Paystack gave no answer (check the
 * reference before re-billing), `declined` (the invoice was emailed instead),
 * `paid`, or `needs_attention` — money arrived but could not be recorded
 * against this invoice (`reason` says why). Informational only: nothing
 * decides a payment from it.
 */
export interface QuoteAutoCharge {
  reference: string;
  mandateId: string;
  state: "pending" | "unknown" | "declined" | "paid" | "needs_attention";
  reason: string | null;
}

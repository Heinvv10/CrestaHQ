// Regenerates the two static assets behind the landing "Buyer World Map":
//   1. public/geo/world-countries.geojson  — country polygons keyed by ISO-A3,
//      coordinate precision reduced to ~1km so the file stays small (it's
//      fetched client-side, lg screens only, so it never touches the mobile
//      bundle).
//   2. src/lib/geo/country-meta.ts          — ISO-A2 → { name, a3, continent,
//      lat, lng } lookup used for choropleth colouring, the leaderboard, the
//      continents/countries stat tiles, and city-dot centroid fallback.
//
// Sources (fetched fresh each run, both public-domain / permissive):
//   - Country polygons: johan/world.geo.json (id = ISO-A3).
//   - Country metadata: mledoze/countries (cca2/cca3/region/latlng).
//
// Run: node scripts/build-geo-assets.mjs
// Re-run only when you want to refresh the geometry — the outputs are
// committed, so a normal build/install never needs network.

import { writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");

const GEO_URL =
  "https://raw.githubusercontent.com/johan/world.geo.json/master/countries.geo.json";
const META_URL =
  "https://raw.githubusercontent.com/mledoze/countries/master/countries.json";

// Round a coordinate to `p` decimals (2 ≈ 1.1km at the equator — plenty for a
// world-scale choropleth). Returns a Number so JSON.stringify emits it bare.
const round = (n, p = 2) => Number(n.toFixed(p));

function roundRing(ring) {
  return ring.map(([x, y]) => [round(x), round(y)]);
}

function roundGeometry(geom) {
  if (geom.type === "Polygon") {
    return { type: "Polygon", coordinates: geom.coordinates.map(roundRing) };
  }
  if (geom.type === "MultiPolygon") {
    return {
      type: "MultiPolygon",
      coordinates: geom.coordinates.map((poly) => poly.map(roundRing)),
    };
  }
  return geom;
}

// mledoze `region` maps cleanly onto the five inhabited continents the map
// counts (Americas is treated as one, matching the "N continents" headline).
const REGION_TO_CONTINENT = {
  Africa: "Africa",
  Americas: "Americas",
  Asia: "Asia",
  Europe: "Europe",
  Oceania: "Oceania",
  Antarctic: "Antarctica",
  "": "Other",
};

async function main() {
  console.log("Fetching sources…");
  const [geo, meta] = await Promise.all([
    fetch(GEO_URL).then((r) => r.json()),
    fetch(META_URL).then((r) => r.json()),
  ]);

  // ---- 1. Geometry -------------------------------------------------------
  const features = geo.features
    // Antarctica is huge, low-signal, and never a buyer — drop it so the file
    // is smaller and the map reads cleaner.
    .filter((f) => f.id && f.id !== "ATA")
    .map((f) => ({
      type: "Feature",
      id: f.id, // ISO-A3
      geometry: roundGeometry(f.geometry),
    }));

  const geoOut = { type: "FeatureCollection", features };
  const geoDir = join(ROOT, "public", "geo");
  await mkdir(geoDir, { recursive: true });
  const geoPath = join(geoDir, "world-countries.geojson");
  await writeFile(geoPath, JSON.stringify(geoOut));
  console.log(
    `Wrote ${geoPath} (${features.length} countries, ${(
      JSON.stringify(geoOut).length / 1024
    ).toFixed(0)}KB)`,
  );

  // ---- 2. Country metadata ----------------------------------------------
  const entries = meta
    .filter((c) => c.cca2 && c.cca3 && Array.isArray(c.latlng))
    .map((c) => {
      const [lat, lng] = c.latlng;
      return [
        c.cca2.toUpperCase(),
        {
          name: c.name?.common ?? c.cca2,
          a3: c.cca3.toUpperCase(),
          continent: REGION_TO_CONTINENT[c.region ?? ""] ?? "Other",
          lat: round(lat, 3),
          lng: round(lng, 3),
        },
      ];
    })
    .sort((a, b) => a[0].localeCompare(b[0]));

  const body = entries
    .map(
      ([code, m]) =>
        `  ${code}: { name: ${JSON.stringify(m.name)}, a3: ${JSON.stringify(
          m.a3,
        )}, continent: ${JSON.stringify(m.continent)}, lat: ${m.lat}, lng: ${
          m.lng
        } },`,
    )
    .join("\n");

  const ts = `// AUTO-GENERATED by scripts/build-geo-assets.mjs — do not edit by hand.
// ISO-3166 alpha-2 -> country metadata for the landing Buyer World Map.

export interface CountryMeta {
  /** Common English name, e.g. "United States". */
  name: string;
  /** ISO-3166 alpha-3, the key into public/geo/world-countries.geojson. */
  a3: string;
  /** Coarse continent bucket (Americas counted as one). */
  continent: string;
  /** Representative centroid latitude (city-dot fallback + leaderboard). */
  lat: number;
  /** Representative centroid longitude. */
  lng: number;
}

export const COUNTRY_META: Record<string, CountryMeta> = {
${body}
};

/** ISO-A2 -> flag emoji, derived from regional-indicator letters (no data). */
export function flagEmoji(alpha2: string): string {
  const cc = alpha2.trim().toUpperCase();
  if (!/^[A-Z]{2}$/.test(cc)) return "\\u{1F3F3}\\uFE0F"; // white flag fallback
  const A = 0x1f1e6;
  return String.fromCodePoint(
    A + (cc.charCodeAt(0) - 65),
    A + (cc.charCodeAt(1) - 65),
  );
}
`;

  const metaPath = join(ROOT, "src", "lib", "geo", "country-meta.ts");
  await mkdir(dirname(metaPath), { recursive: true });
  await writeFile(metaPath, ts);
  console.log(`Wrote ${metaPath} (${entries.length} countries)`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
